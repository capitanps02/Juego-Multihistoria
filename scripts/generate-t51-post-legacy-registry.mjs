import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

const SOURCE_DIR = 'qa/fixtures/t5.1/post-t51-sources';
const OUTPUT = 'src/session/post-t51-legacy-registry.ts';
const check = process.argv.includes('--check');
const sha256 = value => createHash('sha256').update(value).digest('hex');
const journalDigest = (title, label, messages) => sha256(JSON.stringify([title, label, messages]));

export function evidenceForEvents(events) {
  const seen = new Set();
  const evidence = {};
  for (const event of events) {
    if (!event || typeof event.id !== 'string' || seen.has(event.id)) throw new Error(`Invalid/duplicate event id: ${event?.id}`);
    seen.add(event.id);
    const outcomes = new Map((event.outcomes ?? []).map(outcome => [outcome.id, outcome]));
    const journalDigests = {};
    for (const choice of event.choices ?? []) {
      const byOutcome = {};
      for (const outcomeId of choice.outcomeIds ?? []) {
        const outcome = outcomes.get(outcomeId);
        if (!outcome) throw new Error(`Missing outcome ${outcomeId} for ${event.id}/${choice.id}`);
        byOutcome[outcomeId] = journalDigest(event.text?.title ?? '', choice.label, outcome.messages ?? []);
      }
      journalDigests[choice.id] = byOutcome;
    }
    evidence[event.id] = { fingerprint: sha256(JSON.stringify(event)), journalDigests };
  }
  return evidence;
}

export function sourceRecordFromFixture(fixture, filename = '<fixture>') {
  if (!fixture || typeof fixture !== 'object' || Array.isArray(fixture)) throw new Error(`Invalid source fixture ${filename}`);
  if (!Array.isArray(fixture.events)) throw new Error(`Source fixture ${filename} must contain events[]`);
  const actualIdentity = sha256(JSON.stringify(fixture.events));
  if (fixture.contentIdentity !== actualIdentity) {
    throw new Error(`Source fixture ${filename} identity mismatch: declared ${fixture.contentIdentity}, actual ${actualIdentity}`);
  }
  if (typeof fixture.engineBuild !== 'string' || fixture.engineBuild.length === 0) throw new Error(`Source fixture ${filename} missing engineBuild`);
  if (!Array.isArray(fixture.sessionVersions) || fixture.sessionVersions.length === 0) throw new Error(`Source fixture ${filename} missing sessionVersions`);
  return {
    contentIdentity: actualIdentity,
    engineBuild: fixture.engineBuild,
    sessionVersions: fixture.sessionVersions,
    events: evidenceForEvents(fixture.events)
  };
}

export function renderRegistry(records) {
  const sorted = Object.fromEntries(Object.entries(records).sort(([a], [b]) => a.localeCompare(b)));
  return `/* Generated by scripts/generate-t51-post-legacy-registry.mjs. Do not hand-edit. */\n` +
    `import type { LegacyEventEvidence } from "./pre-t51-legacy-registry.js";\n\n` +
    `export interface PostT51ContentEvidenceSource {\n` +
    `  contentIdentity: string;\n` +
    `  engineBuild: string;\n` +
    `  sessionVersions: readonly number[];\n` +
    `  events: Readonly<Record<string, LegacyEventEvidence>>;\n` +
    `}\n\n` +
    `export const POST_T51_CONTENT_SOURCES: Readonly<Record<string, PostT51ContentEvidenceSource>> = ${JSON.stringify(sorted)};\n`;
}

function loadRecords() {
  if (!fs.existsSync(SOURCE_DIR)) return {};
  const records = {};
  for (const name of fs.readdirSync(SOURCE_DIR).filter(name => name.endsWith('.json')).sort()) {
    const fixture = JSON.parse(fs.readFileSync(path.join(SOURCE_DIR, name), 'utf8'));
    const record = sourceRecordFromFixture(fixture, name);
    const expectedName = `${record.contentIdentity}.json`;
    if (name !== expectedName) throw new Error(`Source fixture ${name} must be named ${expectedName}`);
    if (records[record.contentIdentity]) throw new Error(`Duplicate post-T5.1 source ${record.contentIdentity}`);
    records[record.contentIdentity] = record;
  }
  return records;
}

const body = renderRegistry(loadRecords());
if (check) {
  if (!fs.existsSync(OUTPUT)) throw new Error(`Missing generated registry ${OUTPUT}`);
  if (fs.readFileSync(OUTPUT, 'utf8') !== body) throw new Error(`${OUTPUT} is stale; run node scripts/generate-t51-post-legacy-registry.mjs`);
  console.log(JSON.stringify({ checked: true, sources: Object.keys(loadRecords()).length, bytes: Buffer.byteLength(body) }));
} else {
  fs.writeFileSync(OUTPUT, body);
  console.log(JSON.stringify({ generated: OUTPUT, sources: Object.keys(loadRecords()).length, bytes: Buffer.byteLength(body) }));
}
