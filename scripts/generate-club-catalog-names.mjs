import fs from "node:fs";
import path from "node:path";
import { FOOTBALL_CLUBS } from "../dist/catalog/football/index.js";

const root = path.resolve(import.meta.dirname, "..");
const target = path.join(root, "web", "club-catalog-names.js");
const entries = [...FOOTBALL_CLUBS]
  .sort((a, b) => a.id.localeCompare(b.id))
  .map(club => `  ${JSON.stringify(club.id)}: ${JSON.stringify(club.name)}`)
  .join(",\n");
const content = `// Generated by scripts/generate-club-catalog-names.mjs. Do not edit by hand.\nexport const CATALOG_CLUB_NAMES = Object.freeze({\n${entries}\n});\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== content) {
    throw new Error("web/club-catalog-names.js is stale; regenerate it from the football catalog.");
  }
  console.log(`club catalog names OK · ${FOOTBALL_CLUBS.length} clubs`);
} else {
  fs.writeFileSync(target, content);
  console.log(`generated web/club-catalog-names.js · ${FOOTBALL_CLUBS.length} clubs`);
}
