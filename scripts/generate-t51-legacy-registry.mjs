import fs from 'node:fs';
import { createHash } from 'node:crypto';

const SOURCE = 'qa/fixtures/t5.1/pre-t51-event-catalog.json';
const OUTPUT = 'src/session/pre-t51-legacy-registry.ts';
const EXPECTED_IDENTITY = '2e07efd2ea99c4e9ec4c2b20ae89664204f76db2c55a72d567208799c01bccff';
const check = process.argv.includes('--check');
const sha256 = value => createHash('sha256').update(value).digest('hex');

const events = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
if (!Array.isArray(events)) throw new Error('Frozen T5.1 catalog must be an event array');
const serialized = JSON.stringify(events);
const identity = sha256(serialized);
if (identity !== EXPECTED_IDENTITY) throw new Error(`Frozen content identity mismatch: ${identity}`);

const seen = new Set();
const evidence = {};
for (const event of events) {
  if (!event || typeof event.id !== 'string' || seen.has(event.id)) throw new Error(`Invalid/duplicate legacy event id: ${event?.id}`);
  seen.add(event.id);
  const choices = {};
  for (const choice of event.choices ?? []) choices[choice.id] = { label: choice.label, outcomeIds: [...choice.outcomeIds] };
  const outcomes = {};
  for (const outcome of event.outcomes ?? []) outcomes[outcome.id] = { messages: [...outcome.messages] };
  evidence[event.id] = {
    id: event.id,
    fingerprint: sha256(JSON.stringify(event)),
    title: event.text?.title ?? '',
    choices,
    outcomes
  };
}

const body = `/* Generated by scripts/generate-t51-legacy-registry.mjs. Do not hand-edit. */\n` +
`export interface LegacyChoiceEvidence { label: string; outcomeIds: readonly string[]; }\n` +
`export interface LegacyOutcomeEvidence { messages: readonly string[]; }\n` +
`export interface LegacyEventEvidence {\n  id: string;\n  fingerprint: string;\n  title: string;\n  choices: Readonly<Record<string, LegacyChoiceEvidence>>;\n  outcomes: Readonly<Record<string, LegacyOutcomeEvidence>>;\n}\n\n` +
`export const PRE_T51_CONTENT_IDENTITY = ${JSON.stringify(EXPECTED_IDENTITY)};\n` +
`export const PRE_T51_EVENT_COUNT = ${events.length};\n` +
`export const PRE_T51_EVENT_EVIDENCE: Readonly<Record<string, LegacyEventEvidence>> = ${JSON.stringify(evidence)};\n`;

if (check) {
  if (!fs.existsSync(OUTPUT)) throw new Error(`Missing generated registry ${OUTPUT}`);
  const existing = fs.readFileSync(OUTPUT, 'utf8');
  if (existing !== body) throw new Error(`${OUTPUT} is stale; run node scripts/generate-t51-legacy-registry.mjs`);
  console.log(JSON.stringify({ checked: true, identity, events: events.length, bytes: Buffer.byteLength(body) }));
} else {
  fs.writeFileSync(OUTPUT, body);
  console.log(JSON.stringify({ generated: OUTPUT, identity, events: events.length, bytes: Buffer.byteLength(body) }));
}
