import fs from 'node:fs';
import { createHash } from 'node:crypto';

// Recovered from the historical PlayCanvas bundle; the complete catalog hash
// matches the source identity already recorded by pre-T4.1 sessions.
const IDENTITY = '6a48b61a03fefb52e3ee6f1585eb5aaff41acd62380046a4464c932b195a9045';
const SOURCE = 'qa/fixtures/t5.1/pre-t41-event-catalog.json';
const OUTPUT = 'src/session/pre-t41-legacy-registry.ts';
const hash = value => createHash('sha256').update(value).digest('hex');
const events = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
if (hash(JSON.stringify(events)) !== IDENTITY) throw Error('Pre-T4.1 catalog identity mismatch');
if (events.length !== 388 || new Set(events.map(event => event.id)).size !== 388) throw Error('Invalid historical inventory');
const evidence = Object.fromEntries(events.map(event => [event.id, {
  fingerprint: hash(JSON.stringify(event)),
  journalDigests: Object.fromEntries(event.choices.map(choice => [choice.id,
    Object.fromEntries(choice.outcomeIds.map(id => {
      const outcome = event.outcomes.find(row => row.id === id);
      if (!outcome) throw Error(`Missing historical outcome: ${event.id}/${id}`);
      return [id, hash(JSON.stringify([event.text?.title ?? '', choice.label, outcome.messages ?? []]))];
    }))
  ]))
}]));
const body = `/* Generated by scripts/generate-pre-t41-legacy-registry.mjs. Validation only. */\n`
  + `import type { LegacyEventEvidence } from './pre-t51-legacy-registry.js';\n`
  + `export const PRE_T41_CONTENT_IDENTITY = ${JSON.stringify(IDENTITY)};\n`
  + `export const PRE_T41_EVENT_EVIDENCE: Readonly<Record<string, LegacyEventEvidence>> = ${JSON.stringify(evidence)};\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(OUTPUT, 'utf8') !== body) throw Error('Pre-T4.1 evidence registry is stale');
} else fs.writeFileSync(OUTPUT, body);
console.log(JSON.stringify({ identity: IDENTITY, events: events.length, checked: process.argv.includes('--check') }));
