import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const hash = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
const identity = '6a48b61a03fefb52e3ee6f1585eb5aaff41acd62380046a4464c932b195a9045';
const events = JSON.parse(fs.readFileSync('qa/fixtures/t5.1/pre-t51-event-catalog.json'));
assert.equal(hash(events), '2e07efd2ea99c4e9ec4c2b20ae89664204f76db2c55a72d567208799c01bccff');
const old = JSON.parse(fs.readFileSync('qa/fixtures/playcanvas/pre-t41-nano.json'));
const index = events.findIndex(e => e.id === old.id);
assert.notEqual(index, -1);
const expected = structuredClone(events[index]);
for (const outcome of expected.outcomes) {
  if (['WITHDRAW__PRIMARY', 'WITHDRAW__SECONDARY'].includes(outcome.id)) delete outcome.seedTransitions;
}
assert.deepEqual(old, expected, 'Only the two historical seed closures differ');
events[index] = old;
assert.equal(hash(events), identity, 'Reconstructed catalog must match the deployed content identity');
const output = 'src/session/playcanvas-legacy-registry.ts';
const body = `/* Generated by scripts/generate-playcanvas-legacy-registry.mjs. */\nimport { PRE_T51_EVENT_EVIDENCE } from './pre-t51-legacy-registry.js';\nexport const PLAYCANVAS_PRE_T41_IDENTITY = ${JSON.stringify(identity)};\n// All 387 other definitions and all journal semantics are byte-identical.\nexport const PLAYCANVAS_PRE_T41_EVIDENCE = {\n  ...PRE_T51_EVENT_EVIDENCE,\n  CEVT_19_NANO_01: { ...PRE_T51_EVENT_EVIDENCE.CEVT_19_NANO_01, fingerprint: ${JSON.stringify(hash(old))} }\n};\n`;
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(output, 'utf8'), body);
else fs.writeFileSync(output, body);
console.log(`PlayCanvas legacy evidence verified: ${identity}`);
