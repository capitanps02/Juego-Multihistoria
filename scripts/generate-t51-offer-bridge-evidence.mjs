import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

const PRE_SOURCE = 'qa/fixtures/t5.1/pre-t51-event-catalog.json';
const POST_SOURCE_DIR = 'qa/fixtures/t5.1/post-t51-sources';
const OUTPUT = 'src/session/frozen-offer-bridge-evidence.ts';
const check = process.argv.includes('--check');
const sha256 = value => createHash('sha256').update(value).digest('hex');
const VALID_DISPOSITIONS = new Set(['accept', 'reject', 'delegate', 'counter', 'defer']);

function bridgeEvidenceForEvents(events, label) {
  if (!Array.isArray(events)) throw new Error(`${label} must contain an event array`);
  const evidence = {};
  for (const event of events) {
    const bridge = event?.offerBridge;
    if (bridge === undefined) continue;
    if (!event || typeof event.id !== 'string' || !bridge || typeof bridge !== 'object' || Array.isArray(bridge)) {
      throw new Error(`Invalid offerBridge in ${label}/${event?.id}`);
    }
    const actions = bridge.choiceActions;
    if (!actions || typeof actions !== 'object' || Array.isArray(actions)) {
      throw new Error(`Invalid offerBridge.choiceActions in ${label}/${event.id}`);
    }
    const choiceIds = (event.choices ?? []).map(choice => choice.id).sort();
    const mappedIds = Object.keys(actions).sort();
    if (JSON.stringify(choiceIds) !== JSON.stringify(mappedIds)) {
      throw new Error(`Offer bridge ${label}/${event.id} must map every choice exactly once`);
    }
    for (const [choiceId, disposition] of Object.entries(actions)) {
      if (!VALID_DISPOSITIONS.has(disposition)) {
        throw new Error(`Invalid offer disposition ${String(disposition)} in ${label}/${event.id}/${choiceId}`);
      }
    }
    evidence[event.id] = {
      eventFingerprint: sha256(JSON.stringify(event)),
      choiceActions: Object.fromEntries(Object.entries(actions).sort(([a], [b]) => a.localeCompare(b)))
    };
  }
  return evidence;
}

function addSource(records, contentIdentity, events, label) {
  if (!/^[a-f0-9]{64}$/.test(contentIdentity)) throw new Error(`Invalid content identity for ${label}: ${contentIdentity}`);
  if (records[contentIdentity]) throw new Error(`Duplicate offer bridge evidence source ${contentIdentity}`);
  records[contentIdentity] = bridgeEvidenceForEvents(events, label);
}

const records = {};
const preEvents = JSON.parse(fs.readFileSync(PRE_SOURCE, 'utf8'));
addSource(records, sha256(JSON.stringify(preEvents)), preEvents, PRE_SOURCE);

if (fs.existsSync(POST_SOURCE_DIR)) {
  for (const name of fs.readdirSync(POST_SOURCE_DIR).filter(name => name.endsWith('.json')).sort()) {
    const filename = path.join(POST_SOURCE_DIR, name);
    const fixture = JSON.parse(fs.readFileSync(filename, 'utf8'));
    if (!fixture || typeof fixture !== 'object' || !Array.isArray(fixture.events)) throw new Error(`Invalid source fixture ${name}`);
    const actualIdentity = sha256(JSON.stringify(fixture.events));
    if (fixture.contentIdentity !== actualIdentity) throw new Error(`Source fixture ${name} identity mismatch`);
    if (name !== `${actualIdentity}.json`) throw new Error(`Source fixture ${name} has non-canonical filename`);
    addSource(records, actualIdentity, fixture.events, name);
  }
}

const sorted = Object.fromEntries(Object.entries(records).sort(([a], [b]) => a.localeCompare(b)));
const body = `/* Generated by scripts/generate-t51-offer-bridge-evidence.mjs. Do not hand-edit. */\n` +
  `import type { OfferDisposition } from "../simulation/offers.js";\n\n` +
  `export interface FrozenOfferBridgeEventEvidence {\n` +
  `  eventFingerprint: string;\n` +
  `  choiceActions: Readonly<Record<string, OfferDisposition>>;\n` +
  `}\n\n` +
  `export const FROZEN_OFFER_BRIDGE_SOURCES: Readonly<Record<string, Readonly<Record<string, FrozenOfferBridgeEventEvidence>>>> = ${JSON.stringify(sorted)};\n`;

const bridgeCount = Object.values(sorted).reduce((sum, events) => sum + Object.keys(events).length, 0);
if (check) {
  if (!fs.existsSync(OUTPUT)) throw new Error(`Missing generated registry ${OUTPUT}`);
  if (fs.readFileSync(OUTPUT, 'utf8') !== body) throw new Error(`${OUTPUT} is stale; run node scripts/generate-t51-offer-bridge-evidence.mjs`);
  console.log(JSON.stringify({ checked: true, sources: Object.keys(sorted).length, bridges: bridgeCount, bytes: Buffer.byteLength(body) }));
} else {
  fs.writeFileSync(OUTPUT, body);
  console.log(JSON.stringify({ generated: OUTPUT, sources: Object.keys(sorted).length, bridges: bridgeCount, bytes: Buffer.byteLength(body) }));
}
